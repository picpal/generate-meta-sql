-- ⚠️ 인덱스 처리 방침
--   Oracle은 DROP COLUMN 시 그 컬럼을 포함한 인덱스를 정리한다. 단일 컬럼
--   인덱스는 사라지고, 복합 인덱스는 버전·상황에 따라 통째로 사라지거나
--   남은 컬럼의 COLUMN_POSITION이 다시 매겨질 수 있다.
--   추측하지 말고 "물리 DROP COLUMN을 먼저 하고, 영향 인덱스 메타를 모두 걷어낸 뒤,
