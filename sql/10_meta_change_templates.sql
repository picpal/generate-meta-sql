--
--   흐름:  (1) 스냅샷 → (2) 클린 → (3) 03 재실행 → (4) 복원 → (5) 검증
--
-- ★ 왜 §10.3을 골라 쓰지 않는가
--   §10.3은 물리 DROP 블록을 포함한다. 재생성 상황에서 그 블록을 지우는 것을
--   깜빡하면 방금 만든 테이블이 사라진다. 그래서 이 §은 물리 DDL을 아예
--   포함하지 않는다. 통째로 실행해도 실물은 건드리지 않는다.
--
